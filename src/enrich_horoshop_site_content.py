def parse_payload(form_html: str) -> dict[str, Any]:
    parser = FormParser()
    parser.feed(form_html)
    return parser.payload


def admin_blog_title_ids(session: requests.Session, base_url: str) -> dict[str, str]:
    response = session.get(f"{base_url}/adminLegacy/data.php?parent=1001&handler=172&showPages", timeout=60, verify=False)
    response.raise_for_status()
    mapping: dict[str, str] = {}
    for match in re.finditer(r"edit\.php\?id=(\d+)&action=edit&handler=172.*?>([^<>]{4,160})</a>", response.text, re.S):
        title = html.unescape(re.sub(r"\s+", " ", match.group(2)).strip())
        if title:
            mapping[title] = match.group(1)
    return mapping


