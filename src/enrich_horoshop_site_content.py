def block(title: str, paragraphs: list[str], bullets: list[str] | None = None) -> str:
    body = [f"<h2>{html.escape(title)}</h2>"]
    body.extend(f"<p>{p}</p>" for p in paragraphs)
    if bullets:
        body.append("<ul>")
        body.extend(f"<li>{item}</li>" for item in bullets)
        body.append("</ul>")
    return "\n".join(body)


