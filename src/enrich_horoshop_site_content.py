def visible_text_and_images(response_text: str) -> tuple[str, int]:
    clean = html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", response_text))).strip()
    return clean, len(re.findall(r"<img\b", response_text, re.I))


def main() -> int:
    env = load_env()
    base_url = env.get("HOROSHOP_BASE_URL", "https://vsedliarybalky.com.ua").rstrip("/")
    login = env.get("HOROSHOP_LOGIN", "").strip()
    password = env.get("HOROSHOP_PASS", "").strip()
    if not login or not password:
        raise RuntimeError("HOROSHOP_LOGIN/HOROSHOP_PASS are missing in .env")

    session = requests.Session()
    session.headers["User-Agent"] = "fish-sync-site-content-enrichment/1.0"
    auth = session.post(
        f"{base_url}/core-api/admin/security/login",
        json={"login": login, "password": password},
        timeout=60,
        verify=False,
    )
    auth.raise_for_status()

    pages = page_content()
    page_updates = [
        update_page(session, base_url, PAGE_IDS[slug], slug, page)
        for slug, page in pages.items()
    ]

    existing = admin_blog_title_ids(session, base_url)
    today = date.today()
    blog_updates: list[dict[str, Any]] = []
    for index, post in enumerate(all_blog_posts()):
        blog_updates.append(save_blog_post(session, base_url, post, today - timedelta(days=index), existing.get(post["title"])))

    page_verification: dict[str, Any] = {}
    for slug, page in pages.items():
        response = session.get(f"{base_url}/{slug}/?codex_content_verify=1", timeout=60, verify=False)
        text, image_count = visible_text_and_images(response.text)
        page_verification[slug] = {
            "status_code": response.status_code,
            "has_h1": page["h1"] in text,
            "has_demo_text": "демонстраційний магазин" in text.lower(),
            "text_chars": len(text),
            "image_count": image_count,
        }

    blog_verification: dict[str, Any] = {}
    for item in blog_updates:
        response = session.get(f"{base_url}/{item['slug']}/?codex_blog_verify=1", timeout=60, verify=False)
        text, image_count = visible_text_and_images(response.text)
        blog_verification[item["slug"]] = {
            "status_code": response.status_code,
            "has_title": item["title"] in text,
            "text_chars": len(text),
            "image_count": image_count,
        }

    report = {
        "base_url": base_url,
        "pages_updated": page_updates,
        "blog_posts_updated": blog_updates,
        "page_verification": page_verification,
        "blog_verification": blog_verification,
        "image_policy": {
            "provider": "Unsplash and already uploaded free stock assets",
            "license_page": "https://unsplash.com/license",
            "note": "No watermarked images, no competitor scraping, no fake product photos in content pages.",
        },
    }
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


