from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — складні меблі для довгих сесій на березі: стабільна посадка "
        f"і комфорт від ранкового виходу до вечірнього кльову.",
        f"{ctx.display_name} — продумане сидіння для рибалки: швидко розкладається, впевнено "
        f"стоїть на нерівному березі та витримує щоденне використання.",
        f"{ctx.display_name} — комфорт, який змінює риболовлю: спина не втомлюється, а руки "
        f"завжди вільні для роботи зі снастю.",
    ]
    usage = [
        "Регульовані ніжки компенсують ухил і м'який ґрунт; широкі опори не провалюються "
        "в пісок та мул.",
        "Каркас тримає заявлене навантаження із запасом, тканина дихає влітку та легко "
        "чиститься від бруду й луски.",
        "У складеному вигляді займає мінімум місця в багажнику; вага дозволяє без зусиль "
        "доносити його до точки ловлі.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Матеріал", "Максимальне навантаження", "Розміри"],
    )
