from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — готовий монтаж: дістали з упаковки, пристебнули до основної "
        f"волосіні — і снасть готова до закидання.",
        f"{ctx.display_name} — змонтована оснастка з правильною геометрією: всі елементи "
        f"підібрані та зв'язані так, як це робить досвідчений рибалка.",
        f"{ctx.display_name} — готове рішення для тих, хто цінує час на водоймі: жодного "
        f"в'язання вузлів на березі, лише риболовля.",
        f"{ctx.display_name} — монтаж заводського виконання зі стабільною якістю вузлів: "
        f"кожне з'єднання протестовано на міцність.",
    ]
    usage = [
        "Зручно мати кілька запасних монтажів у коробці: обрив на корчах не зупинить "
        "риболовлю — переоснащення займає хвилину.",
        "Підходить і початківцям, які ще вчаться в'язати оснастки, і досвідченим рибалкам "
        "як швидкий запас на активному клюванні.",
        "Компоненти підібрані збалансовано: гачки гострі, фурнітура тримає навантаження, "
        "матеріал повідця відповідає призначенню монтажу.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Кількість відводів", "Вага", "Розмір"],
    )
