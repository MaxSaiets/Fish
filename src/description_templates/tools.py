from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — інструмент, який спрощує підготовку монтажу та роботу "
        f"зі снастю просто на водоймі.",
        f"{ctx.display_name} — практичний помічник рибалки: економить час на в'язанні "
        f"оснасток і роботі з дрібними елементами.",
        f"{ctx.display_name} — інструмент для акуратної роботи з оснасткою: те, що робить "
        f"підготовку швидшою, а результат — стабільнішим.",
    ]
    usage = [
        "Компактний розмір дозволяє тримати інструмент у кишені жилета чи монтажній "
        "коробці — він завжди під рукою в потрібний момент.",
        "Матеріали витримують вологу та польові умови: інструмент працює сезонами без "
        "люфтів і корозії.",
        "Стане в пригоді і на березі, і вдома при підготовці до риболовлі: одна дрібниця, "
        "яка помітно економить час.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Матеріал", "Призначення", "Довжина", "Вага"],
    )
