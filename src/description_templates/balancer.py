from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — балансир для зимової ловлі з-під льоду: горизонтальна гра "
        f"імітує поранену рибку — головну ціль судака, щуки та окуня.",
        f"{ctx.display_name} — зимовий балансир зі стабільною розгойдкою: на паузі описує "
        f"характерну вісімку, що збуджує навіть пасивного хижака.",
        f"{ctx.display_name} — балансир для активного пошуку риби по лунках: швидко виходить "
        f"на робочий горизонт і чітко відгукується на анімацію.",
    ]
    usage = [
        "Класична проводка — підкидання з паузою: на зависанні балансир планерує в сторону, "
        "саме в цей момент трапляється більшість поклювок.",
        "Гострі гачки та міцні кільця реалізують і обережні тички, і впевнені удари; "
        "фарбування тримається після контактів із льодом та зубами хижака.",
        "Працює на середніх і великих глибинах: маса тіла дозволяє швидко обловлювати "
        "лунки, не чекаючи довгого занурення.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Вага", "Довжина", "Розмір", "Колір", "Матеріал", "Призначення"]
    )
