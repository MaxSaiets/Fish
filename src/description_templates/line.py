from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    line_type = ctx.common_params.get("Тип", "").lower()
    is_braid = "плет" in line_type or "шнур" in line_type
    if is_braid:
        intro = [
            f"{ctx.display_name} — плетений шнур з щільним плетінням і мінімальним розтягом: "
            f"кожен дотик до приманки передається в руку миттєво.",
            f"{ctx.display_name} — шнур для джига та твічингу, де потрібен повний контроль "
            f"проводки та миттєва підсічка на будь-якій дистанції.",
            f"{ctx.display_name} — зносостійкий плетений шнур з рівним калібруванням по всій "
            f"довжині: рівно лягає на шпулю та далеко летить.",
        ]
        usage = [
            "Гладке покриття зменшує тертя в кільцях і додає дальності закидання, а стійкість "
            "до стирання дозволяє ловити біля ракушняка та корчів.",
            "Тримає вузли та зберігає міцність після контакту з перешкодами; колір не линяє "
            "після перших риболовель.",
        ]
    else:
        intro = [
            f"{ctx.display_name} — монофільна волосінь з контрольованим розтягом, який амортизує "
            f"ривки риби та страхує від обривів на виважуванні.",
            f"{ctx.display_name} — волосінь з рівним калібруванням діаметра по всій розмотці: "
            f"передбачувана міцність вузлів і стабільна робота оснастки.",
            f"{ctx.display_name} — універсальна волосінь для поплавкової та донної ловлі: м'яка, "
            f"слухняна на шпулі, без «пам'яті» після намотування.",
        ]
        usage = [
            "Підійде як основна волосінь і для повідців: вузли тримає впевнено, поверхня стійка "
            "до стирання об кільця та дно водойми.",
            "Прозорість у воді робить оснастку менш помітною для обережної риби, а еластичність "
            "прощає різкі підсічки.",
        ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Призначення", "Діаметр", "Розривне навантаження", "Довжина розмотки"])
