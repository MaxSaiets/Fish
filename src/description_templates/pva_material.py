from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    pva_type = ctx.common_params.get("Тип", "PVA-матеріал").lower()
    intro = [
        f"{ctx.display_name} — {pva_type} для точкової подачі корму: прикормка опиняється "
        f"впритул до насадки, де її і знайде короп.",
        f"{ctx.display_name} — {pva_type} з контрольованим часом розчинення: монтаж долітає "
        f"до точки цілим і розкривається вже на дні.",
        f"{ctx.display_name} — {pva_type} для акуратних закормів без розсіювання: працює "
        f"навіть на дальніх дистанціях і течії.",
    ]
    usage = [
        "Розчиняється без залишку та запаху, не насторожуючи рибу; швидкість розчинення "
        "залежить від температури води — враховуйте сезон.",
        "Тримайте матеріал у щільно закритій упаковці подалі від вологи — тоді він "
        "збереже властивості до кінця сезону.",
        "Поєднується з пелетсом, дробленими бойлами та сипучками з низькою вологістю; "
        "вологі суміші для ПВА не годяться.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Матеріал", "Умови використання", "Довжина", "Діаметр", "Розмір"],
    )
