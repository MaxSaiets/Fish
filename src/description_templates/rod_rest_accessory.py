from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — елемент організації робочого місця: вудилища стоять "
        f"стабільно й завжди готові до підсічки.",
        f"{ctx.display_name} — аксесуар для підставок і род-подів: надійна фіксація снасті "
        f"на будь-якому березі — від піску до каміння.",
        f"{ctx.display_name} — дрібниця, що визначає комфорт стаціонарної ловлі: правильне "
        f"положення вудилищ і миттєвий доступ до них.",
    ]
    usage = [
        "Сумісний зі стандартними різьбами стійок і род-подів; встановлення та "
        "регулювання займають секунди.",
        "Метал із захисним покриттям переживає дощ, мул і пісок без корозії; "
        "конструкція тримає навантаження потужних коропових снастей.",
        "Зручно мати запас під різні умови: м'який ґрунт, високий очерет чи бетонна "
        "дамба вимагають різної постановки.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Довжина", "Матеріал"])
