from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    aroma = ctx.param("Аромат", "Смак", "Аромат/варіант")
    aroma_bit = f" Аромат — {aroma.lower()}." if aroma and not aroma[0].isdigit() else ""

    family = ctx.family
    if family == "pop_up_bait":
        intro = [
            f"{ctx.display_name} — плаваюча насадка pop-up з стійкою плавучістю, яка тримає "
            f"гачок над дном і робить презентацію помітною для коропа.{aroma_bit}",
            f"{ctx.display_name} — pop-up для важких умов: мул, водорості, килим з опалого "
            f"листя — насадка завжди залишається над сміттям, у полі зору риби.{aroma_bit}",
            f"{ctx.display_name} — яскрава плаваюча насадка для одиночної подачі та снеговиків: "
            f"плавучість зберігається багато годин.{aroma_bit}",
        ]
        usage = [
            "Працює у монтажах чод-риг, снеговик та класичному волосяному: підбирайте висоту "
            "подйому під активність риби. Зберігайте банку щільно закритою.",
            "Контрастний колір і насичений аромат роблять насадку точкою прицілу навіть на "
            "закормленому свімі. Добре дюпається в ліквідах для підсилення сигналу.",
        ]
    elif family == "boilie":
        intro = [
            f"{ctx.display_name} — насадкові бойли зі збалансованим складом: працюють і по "
            f"дикому коропу, і на запресованих платниках.{aroma_bit}",
            f"{ctx.display_name} — бойли з щільною структурою, що добре тримаються на волоссі "
            f"та не розмиваються дрібнорибʼям.{aroma_bit}",
            f"{ctx.display_name} — бойли на основі робочої харчової бази з атрактантами: "
            f"створюють стійкий ароматичний слід у точці ловлі.{aroma_bit}",
        ]
        usage = [
            "Використовуйте як насадку на волосяному монтажі та як прикормку в ПВА-пакетах "
            "чи через кобру. Перед сесією частину бойлів можна подрібнити для активнішого старту.",
            "Поєднуються з pop-up у монтажі снеговик; для підсилення сигналу замочіть бойли "
            "в однойменному ліквіді за добу до риболовлі.",
        ]
    elif family == "pellets":
        intro = [
            f"{ctx.display_name} — пелетс для прикормлювання та насадки: рівномірна фракція, "
            f"стабільний час розчинення, робоча ароматика.{aroma_bit}",
            f"{ctx.display_name} — пелетс із пресованої кормової бази: повільно віддає аромат, "
            f"утримуючи рибу в точці без перегодовування.{aroma_bit}",
            f"{ctx.display_name} — гранули для фідерної та коропової ловлі, що створюють "
            f"привабливий кормовий стіл на дні.{aroma_bit}",
        ]
        usage = [
            "Дрібна фракція — у годівницю та спод-мікс, велика — як насадка на волоссі чи в "
            "бандажі. Час розчинення підбирайте під інтенсивність клювання.",
            "Працює самостійно і в міксах із зерновими; для платників обирайте швидкорозчинний "
            "пелетс, для рік — щільніший.",
        ]
    elif family == "liquid_attractant":
        intro = [
            f"{ctx.display_name} — рідкий атрактант для підсилення сигналу прикормки та насадок: "
            f"миттєво поширюється у воді й збирає рибу до точки.{aroma_bit}",
            f"{ctx.display_name} — ліквід з концентрованою ароматикою: працює навіть у холодній "
            f"воді, де сухі суміші розкриваються повільно.{aroma_bit}",
            f"{ctx.display_name} — добавка для дюпання насадок, замочування бойлів і пропитки "
            f"ПВА-міксів.{aroma_bit}",
        ]
        usage = [
            "Додавайте у прикормку на етапі зволоження, дюпайте насадку перед закиданням або "
            "проливайте спод-мікс — дозування легко контролювати.",
            "Невелика витрата робить флакон економним: на сесію достатньо кількох порцій, "
            "а ефект тримається до перезакидання оснастки.",
        ]
    elif family == "bait_mix":
        intro = [
            f"{ctx.display_name} — готовий мікс для створення кормової точки: збалансоване "
            f"поєднання фракцій під різні дистанції та глибини.{aroma_bit}",
            f"{ctx.display_name} — кормова суміш, що поєднує великі та дрібні частки: швидкий "
            f"старт і довге утримання риби на точці.{aroma_bit}",
        ]
        usage = [
            "Подається сподом, ракетою або у ПВА: зволожте до потрібної липкості та подавайте "
            "порціями, спостерігаючи за виходами риби.",
            "Добре приймає ліквіди й бустери — підлаштовуйте аромат під сезон і водойму.",
        ]
    else:
        intro = [
            f"{ctx.display_name} — зернова насадка та прикормка природного походження: звична "
            f"їжа для коропа, ляща та карася.{aroma_bit}",
            f"{ctx.display_name} — підготовлені зернові для прикормлювання та насадки: правильна "
            f"консистенція без закисання.{aroma_bit}",
            f"{ctx.display_name} — робоча зернова база для створення кормового столу: помітна, "
            f"поживна, з натуральним ароматом.{aroma_bit}",
        ]
        usage = [
            "Підходить для волосяного монтажу, насадки на гачок і додавання у прикормувальні "
            "суміші; зручно подавати сподом або в ПВА.",
            "Поєднуйте з бойлами та пелетсом у міксах — різнорідна фракція довше утримує рибу "
            "в точці ловлі.",
        ]
    return build_standard_description(ctx, intro, usage, ["Тип насадки", "Тип суміші", "Плавучість", "Аромат", "Об'єм", "Вага"])
