from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    shape = ctx.param("Форма грузила", "Форма")
    shape_bit = f" Форма — {shape.lower()}." if shape and not shape[0].isdigit() else ""
    intro = [
        f"{ctx.display_name} — грузило для побудови оснастки та утримання монтажу в точці "
        f"ловлі.{shape_bit}",
        f"{ctx.display_name} — грузило з рівномірним литтям без раковин: вага відповідає "
        f"маркуванню, монтаж працює передбачувано.{shape_bit}",
        f"{ctx.display_name} — грузило для дальнього та точного закидання: аеродинаміка форми "
        f"стабілізує політ оснастки.{shape_bit}",
        f"{ctx.display_name} — робоче грузило для донних монтажів: впевнено тримає дно і не "
        f"котиться на течії.{shape_bit}",
    ]
    usage = [
        "Підбирайте вагу під дистанцію, глибину та силу течії: правильний баланс пришвидшує "
        "досягнення дна без перевантаження вудилища.",
        "Матове покриття не відлякує обережну рибу та захищає метал від окислення; вушко "
        "або вертлюг обертається вільно, не закручуючи оснастку.",
        "Універсальне рішення для фідерних і коропових монтажів: інлайн, патерностер, "
        "безпечна кліпса — грузило стане в кожному з них.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Форма грузила", "Матеріал", "Вага", "Призначення"],
    )
