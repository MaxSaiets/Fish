from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — кивок для чутливої індикації поклювки: показує навіть "
        f"найделікатніший дотик риби до приманки.",
        f"{ctx.display_name} — кивок, що задає правильну гру мормишці: стабільна частота "
        f"без зривів і паразитних коливань.",
        f"{ctx.display_name} — індикатор поклювки для тонких зимових оснасток: чітко працює "
        f"і на підйом, і на притискання.",
    ]
    usage = [
        "Підбирайте жорсткість під вагу приманки: правильно навантажений кивок згинається "
        "під 45 градусів і миттєво реагує на поклювку.",
        "Матеріал зберігає пружність на морозі та не ламається на згинах — кивка вистачає "
        "не на один сезон.",
        "Яскравий кінчик читається на тлі снігу та темної води в сутінках.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Матеріал", "Сезон", "Довжина"])
