from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — ліхтар для риболовлі та кемпінгу: яскраве світло там, де воно "
        f"потрібне, — на нічній сесії, у наметі чи по дорозі до точки.",
        f"{ctx.display_name} — надійне джерело світла для темної пори: компактний, з рівним "
        f"пучком і зручним керуванням наосліп.",
        f"{ctx.display_name} — ліхтар, з яким нічна риболовля стає комфортною: руки вільні, "
        f"робоча зона освітлена, монтаж видно.",
    ]
    usage = [
        "Кілька режимів яскравості дозволяють економити заряд, а вологозахист корпусу "
        "витримує росу й дощ на березі.",
        "Зручне кріплення й ергономіка дають працювати зі снастю однією рукою; заряду "
        "вистачає на повну нічну сесію.",
        "Стане в пригоді і на риболовлі, і в туристичному поході, і як аварійне світло вдома.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Джерело живлення", "Матеріал", "Призначення"])
