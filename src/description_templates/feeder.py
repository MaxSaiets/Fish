from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — годівниця для точної подачі корму в точку ловлі: стабільний "
        f"політ і передбачуване положення на дні.",
        f"{ctx.display_name} — фідерна годівниця з продуманою вагою та геометрією: швидко "
        f"досягає дна і не зміщується з точки на течії.",
        f"{ctx.display_name} — робоча годівниця для регулярних закормів: корм вивільняється "
        f"з правильною швидкістю, утримуючи рибу в зоні ловлі.",
    ]
    usage = [
        "Підбирайте вагу під дистанцію та силу течії: важчі тримають точку на річці, "
        "легші делікатно працюють на ставку.",
        "Кріплення сумісне з класичними фідерними монтажами: патерностер, інлайн, "
        "петля Гарднера — переоснащення займає хвилину.",
        "Метал і пластик конструкції витримують регулярні закиди сезон за сезоном "
        "без деформацій.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Підтип", "Призначення", "Вага", "Матеріал"],
    )
