from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — захист вудилищ у дорозі: жорстка форма і щільний матеріал "
        f"бережуть бланки від ударів та перегинів.",
        f"{ctx.display_name} — чохол для транспортування снастей: спорядження приїде на "
        f"водойму цілим, сухим і готовим до роботи.",
        f"{ctx.display_name} — продумане зберігання вудилищ вдома та в дорозі: кожна снасть "
        f"на своєму місці, нічого не плутається і не треться.",
    ]
    usage = [
        "Місткість дозволяє перевозити кілька комплектів одразу; внутрішні перегородки "
        "не дають кільцям і вершинкам контактувати між собою.",
        "Зносостійка тканина і міцні блискавки розраховані на роки активних виїздів; "
        "ручки та лямки не ріжуть плече навіть із повним завантаженням.",
        "Зручний і в авто, і в громадському транспорті: компактні габарити при повному "
        "захисті вмісту.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Конструкція", "Довжина", "Кількість секцій", "Матеріал"],
    )
