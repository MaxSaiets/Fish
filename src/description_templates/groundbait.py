from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    aroma = ctx.param("Аромат", "Аромат/склад", "Аромат/варіант")
    aroma_bit = f" Робочий аромат — {aroma.lower()}." if aroma and not aroma[0].isdigit() else ""
    intro = [
        f"{ctx.display_name} — прикормка для формування кормової точки та утримання риби "
        f"в зоні ловлі.{aroma_bit}",
        f"{ctx.display_name} — прикормувальна суміш зі збалансованою механікою: активно працює "
        f"в товщі води та збирає рибу до точки.{aroma_bit}",
        f"{ctx.display_name} — прикормка з робочою фракцією, що швидко стартує і довго утримує "
        f"рибу на точці, не перегодовуючи її.{aroma_bit}",
        f"{ctx.display_name} — суміш для активної риболовлі: створює стовп каламуті та ароматичний "
        f"слід, який збирає рибу з течії.{aroma_bit}",
    ]
    usage = [
        "Використовується у поплавковій, фідерній та короповій ловлі: зволожуйте поетапно до "
        "потрібної консистенції — від активної пилючої до в'язкої для течії.",
        "Добре працює і самостійно, і в міксах з зерновими або пелетсом; для точкової подачі "
        "ліпиться в щільні кулі, для годівниці — розсипчаста консистенція.",
        "Просте приготування прямо на водоймі: додавайте воду невеликими порціями та дайте "
        "суміші настоятися 10-15 хвилин перед стартовим закормом.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Консистенція", "Аромат", "Аромат/склад", "Вага"],
    )
