from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    reel_type = ctx.common_params.get("Тип", "безінерційна котушка").lower()
    intro = [
        f"{ctx.display_name} — {reel_type} з плавним ходом механізму та рівним намотуванням, "
        f"яке прибирає скидання петель навіть із тонкими шнурами.",
        f"{ctx.display_name} — {reel_type} з чутливим фрикціоном: тонке налаштування дозволяє "
        f"гасити ривки риби, зберігаючи цілими тонкі повідці.",
        f"{ctx.display_name} — {reel_type} зі збалансованим ротором, що працює без вібрацій "
        f"на будь-якій швидкості підмотування.",
        f"{ctx.display_name} — {reel_type} для регулярної риболовлі: ресурс механізму та захист "
        f"від води розраховані на повний сезон без обслуговування.",
    ]
    usage = [
        "Підшипники в ключових вузлах прибирають люфти та забезпечують плавність, а металевий "
        "вал і надійна головна пара тримають навантаження на виважуванні.",
        "Шпуля з рівним укладанням додає дальності закидання; запасна намотка дозволяє швидко "
        "змінити діаметр волосіні під умови ловлі.",
        "Зручна ручка та продумана ергономіка зменшують втому за день активної ловлі; "
        "ротор миттєво відгукується на оберти — контроль приманки завжди в руці.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Тип", "Розмір", "Підшипники", "Передаточне число", "Матеріал корпусу", "Ємність шпулі", "Вага"]
    )
