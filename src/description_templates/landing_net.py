from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — надійний помічник на фінальній стадії виважування: саме "
        f"біля берега сходить найбільше риби.",
        f"{ctx.display_name} — елемент оснащення для акуратного прийому риби: міцна "
        f"конструкція і зручна робота однією рукою.",
        f"{ctx.display_name} — те, що перетворює поклювку на улов: впевнений підбір риби "
        f"без ризику обриву повідця на останніх метрах.",
    ]
    usage = [
        "Сітка не травмує рибу та не чіпляється за гачки — актуально для принципу "
        "«впіймав-відпусти» та делікатних оснасток.",
        "Ручка тримає навантаження при підборі трофея на витягнутій руці; стики не "
        "люфтять після сезону активної ловлі.",
        "Складна конструкція компактна у транспортуванні та розкладається за секунди "
        "в момент, коли рахунок іде на миті.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Довжина", "Розмір", "Матеріал"],
    )
