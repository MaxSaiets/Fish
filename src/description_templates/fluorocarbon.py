from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — флюорокарбон із коефіцієнтом заломлення, близьким до води: "
        f"повідець практично зникає з поля зору обережної риби.",
        f"{ctx.display_name} — повідковий флюорокарбон з високою стійкістю до стирання: "
        f"тримає контакт із ракушняком, камінням і зубами хижака.",
        f"{ctx.display_name} — флюорокарбон для делікатних оснасток: жорсткість матеріалу "
        f"зменшує перехлести та тримає форму монтажу.",
    ]
    usage = [
        "Найкраще розкривається на прозорій воді та запресованих водоймах, де звичайна "
        "волосінь ріже кількість поклювок.",
        "Швидко тоне і не змінює властивостей від ультрафіолету та перепадів температур — "
        "працює і влітку, і на зимових лунках.",
        "Вузли в'яжуться надійно за умови змочування; для максимальної міцності "
        "використовуйте вузли для жорстких матеріалів.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Матеріал", "Діаметр", "Розривне навантаження"])
