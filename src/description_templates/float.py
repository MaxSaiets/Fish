from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — поплавок з чутливою огрузкою: показує і впевнене клювання, "
        f"і обережний дотик до насадки.",
        f"{ctx.display_name} — поплавок зі стійким до води покриттям: антена зберігає яскравість "
        f"сезон за сезоном, тіло не набирає воду.",
        f"{ctx.display_name} — збалансований поплавок, що тримає вертикаль на хвилі та течії "
        f"і не лягає при підтягуваннях.",
        f"{ctx.display_name} — поплавок для точної подачі насадки: вантажопідйомність дозволяє "
        f"швидко вивести оснастку на робочу глибину.",
    ]
    usage = [
        "Яскрава антена читається на будь-якому тлі води; кіль стабілізує поплавок при "
        "проводці та притримуваннях на течії.",
        "Підбирайте огрузку так, щоб над водою лишалась тільки антена — тоді навіть найделікатніше "
        "клювання карася не залишиться непоміченим.",
        "Кріплення тримає поплавок надійно та дозволяє швидко замінити його без перев'язування "
        "всієї оснастки.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Колір", "Вага", "Розмір"],
    )
