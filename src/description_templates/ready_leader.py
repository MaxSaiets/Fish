from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — готовий повідець для швидкого монтажу: пристебнули до оснастки "
        f"і ловите, без в'язання вузлів на березі.",
        f"{ctx.display_name} — повідець заводського виконання зі стабільною якістю з'єднань: "
        f"кожен вузол затягнутий рівно і протестований на міцність.",
        f"{ctx.display_name} — готовий повідець для тих, хто цінує час на риболовлі та "
        f"передбачувану роботу оснастки за будь-якої погоди.",
    ]
    usage = [
        "Зручно мати запас повідців різної довжини та міцності: обрив на зачепі не зупинить "
        "ловлю, а заміна займе менше хвилини навіть на морозі.",
        "Матеріал повідця підібраний під призначення монтажу: він тримає вузли, не втрачає "
        "міцності у воді та не відлякує обережну рибу.",
        "Повторюваність — головна перевага готових повідців: кожен наступний працює так само, "
        "як попередній, тож легко відтворити робочу оснастку.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Матеріал", "Призначення", "Довжина", "Розмір"])
