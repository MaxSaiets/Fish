from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    ind_type = ctx.common_params.get("Тип", "сигналізатор клювання").lower()
    intro = [
        f"{ctx.display_name} — {ind_type} для впевненого контролю снастей вдень і вночі: "
        f"жодна поклювка не залишиться непоміченою.",
        f"{ctx.display_name} — {ind_type}, що звільняє очі та руки: можна готувати наступну "
        f"оснастку чи відпочивати, не випускаючи ловлю з-під контролю.",
        f"{ctx.display_name} — {ind_type} для стаціонарної ловлі на кілька вудилищ: чітке "
        f"розрізнення, яка саме снасть спрацювала.",
    ]
    usage = [
        "Чутливість зчитує і впевнені потяжки, і обережні поклювки «на ослаблення»; "
        "захист від вологи дозволяє працювати в дощ і туман.",
        "Кріплення сумісне зі стандартними підставками та род-подами — встановлення "
        "займає секунди.",
        "Незамінний на нічній риболовлі: сигнал чутно з намету, а індикація підкаже "
        "напрямок руху риби.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Підтип", "Джерело живлення", "Комплектація", "Довжина"])
