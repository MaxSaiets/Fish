from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    lure_type = ctx.common_params.get("Тип", "воблер").lower()
    intro = [
        f"{ctx.display_name} — {lure_type} з реалістичною грою та деталізованим забарвленням, "
        f"що імітує поранену рибку — головну ціль хижака.",
        f"{ctx.display_name} — {lure_type} зі стабільною роботою на заявленому заглибленні: "
        f"тримає горизонт і не збивається з гри на течії.",
        f"{ctx.display_name} — {lure_type} для точкової ловлі по місцях стоянки хижака: "
        f"бровки, корчі та межі трави.",
        f"{ctx.display_name} — {lure_type} з якісною фурнітурою та гострими трійниками, "
        f"що реалізують навіть обережні поклювки.",
    ]
    usage = [
        "Працює на рівномірній проводці, твічингу та stop&go: на паузі воблер зависає або "
        "повільно спливає, провокуючи навіть ситу рибу. Основні трофеї — щука, окунь, судак.",
        "Продумане балансування дозволяє далеко закидати приманку та обловлювати точки, "
        "недосяжні для звичайних блешень, а шумова капсула додатково приваблює хижака.",
        "Найрезультативніший у періоди активності малька: підбирайте темп проводки під настрій "
        "риби — від агресивного твічингу до плавних потяжок із довгими паузами.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Тип", "Довжина", "Вага", "Заглиблення", "Плавучість", "Колір"]
    )
