from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — спінінгове вудилище з чутливим бланком, який передає в руку "
        f"і поклювку, і торкання приманкою дна.",
        f"{ctx.display_name} — вудилище для ловлі хижака, де важливі точність закидання "
        f"та контроль приманки на всій дистанції проводки.",
        f"{ctx.display_name} — збалансований спінінг: легка вершинка відпрацьовує анімацію, "
        f"а потужний комель впевнено гасить ривки риби на виважуванні.",
        f"{ctx.display_name} — робочий інструмент для джига, твічингу та залізних приманок "
        f"у межах тестового діапазону.",
    ]
    usage = [
        "Кільця рівномірно розподіляють навантаження по бланку та дружать із плетеним шнуром, "
        "а надійний котушкотримач фіксує котушку без люфтів навіть після сезону активної ловлі.",
        "Підійде для берегової та човнової риболовлі: швидкий стрій дає різку підсічку, "
        "а запас потужності дозволяє форсувати виважування у корчах та траві.",
        "Зручне руків'я не втомлює кисть за повний день риболовлі, бланк прощає помилки "
        "на закиданні та зберігає чутливість у холодну пору.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Тип вудилища", "Матеріал", "Тест", "Довжина", "Стрій"]
    )
