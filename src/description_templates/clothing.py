from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    cl_type = ctx.common_params.get("Тип", "екіпірування").lower()
    intro = [
        f"{ctx.display_name} — {cl_type} для риболовлі та активного відпочинку: розраховано "
        f"на польові умови й часті виїзди.",
        f"{ctx.display_name} — {cl_type}, що тримає комфорт у мінливу погоду: захищає від "
        f"вологи, вітру та прохолоди на березі.",
        f"{ctx.display_name} — практичний {cl_type} для рибалки: продумані деталі, зносостійкі "
        f"матеріали, зручність у русі.",
    ]
    usage = [
        "Матеріали підібрані під тривале носіння: тканина дихає, шви не натирають, а догляд "
        "зводиться до звичайного прання чи протирання.",
        "Зручна посадка не сковує рухи при закиданні та виважуванні; кишені й регулювання "
        "розташовані так, щоб усе потрібне було під рукою.",
        "Підійде для риболовлі в будь-який сезон у своїй температурній зоні, а також для "
        "полювання, туризму та роботи на повітрі.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Матеріал", "Колір", "Розмір", "Країна-виробник", "Призначення"],
    )
