from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    lure_type = ctx.common_params.get("Тип", "блешня").lower()
    intro = [
        f"{ctx.display_name} — {lure_type} зі стабільною грою та якісним гальванічним покриттям, "
        f"яке довго зберігає блиск і помітність у воді.",
        f"{ctx.display_name} — {lure_type} для активного пошуку хижака: метал дає сильні коливання "
        f"та відблиски, які збирають рибу з великої відстані.",
        f"{ctx.display_name} — перевірена часом {lure_type}, що заводиться з перших обертів котушки "
        f"і тримає гру як на течії, так і в стоячій воді.",
        f"{ctx.display_name} — {lure_type} з точним балансуванням тіла: летить далеко, не штопорить "
        f"на швидкій проводці та не залипає на повільній.",
    ]
    usage = [
        "Працює по окуню, щуці та жереху на рівномірній проводці; на паузах тіло планерує, "
        "додаючи поклювок у холодній воді. Гострий трійник надійно тримає рибу.",
        "Класика для річки та озера: проводка за течією, проти неї або апстрім — блешня тримає "
        "горизонт і не перекручує волосінь завдяки якісному вертлюгу.",
        "Підходить і початківцям, і досвідченим спінінгістам: достатньо рівномірної проводки, "
        "щоб приманка працювала, а зміна темпу лише додає реалістичності.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Тип", "Вага", "Розмір", "Колір", "Кількість в упаковці"]
    )
