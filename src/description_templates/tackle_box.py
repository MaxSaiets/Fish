from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — місткий органайзер для системного зберігання снастей: "
        f"кожна дрібниця на своєму місці.",
        f"{ctx.display_name} — зберігання, з яким збори на риболовлю займають хвилини: "
        f"приманки, фурнітура та аксесуари розкладені й захищені.",
        f"{ctx.display_name} — практичне рішення для перевезення спорядження: міцні стінки "
        f"захищають вміст від ударів і вологи.",
    ]
    usage = [
        "Продумані відділення дозволяють розкласти приманки за типами й розмірами — "
        "потрібна знаходиться за секунди навіть в активному клюванні.",
        "Матеріал тримає форму на спеці й морозі, застібки не розбовтуються від "
        "регулярного використання.",
        "Зручно комбінувати кілька коробок під різні стилі ловлі: джиг, поплавок, "
        "фідер — кожен комплект завжди готовий до виїзду.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Комплектація", "Розміри", "Матеріал"],
    )
