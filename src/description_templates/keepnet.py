from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — садок для дбайливого зберігання улову: риба залишається "
        f"живою та неушкодженою до кінця риболовлі.",
        f"{ctx.display_name} — місткий садок для активної ловлі: швидке закидання риби "
        f"без зайвих рухів, що лякають зграю.",
        f"{ctx.display_name} — садок, з яким улов зберігається у природному середовищі: "
        f"актуально і для спортсменів, і для аматорів.",
    ]
    usage = [
        "М'яка безвузлова сітка не знімає луску та слиз — риба після зважування "
        "повертається у водойму без пошкоджень.",
        "Кільця тримають форму на течії, а довжина дозволяє опустити садок на глибину, "
        "де вода прохолодніша навіть у спеку.",
        "Швидко сохне та компактно складається — в рюкзаку займає мінімум місця.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Призначення", "Форма", "Довжина", "Розмір", "Матеріал"],
    )
