from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    lure_type = ctx.common_params.get("Тип", "силіконова приманка").lower()
    intro = [
        f"{ctx.display_name} — {lure_type} з активною грою на падінні та рівномірній проводці, "
        f"розрахована на джигові й мікроджигові монтажі.",
        f"{ctx.display_name} — {lure_type}, що тримає стабільну гру навіть на повільній проводці "
        f"та добре працює по пасивному хижаку.",
        f"{ctx.display_name} — {lure_type} для ловлі окуня, судака та щуки на джиг: м'який матеріал "
        f"дає природні коливання тіла на будь-якій стадії проводки.",
        f"{ctx.display_name} — {lure_type} з виразною геометрією та м'яким силіконом, який риба "
        f"довше тримає в пащі, даючи час на впевнену підсічку.",
    ]
    usage = [
        "М'який силікон повторює рухи живої рибки чи рачка та провокує атаку навіть неактивного "
        "хижака. Монтується на джиг-голівку, офсетний гачок, у дроп-шот або каролінську оснастку.",
        "Приманка однаково впевнено працює на класичному джигу та на рознесених монтажах: "
        "відвідний повідець, спліт-шот, дроп-шот. Силікон тримає форму після поклювок.",
        "Найкраще розкривається на ступінчастій проводці з паузами: на падінні хвіст продовжує "
        "грати, що часто і викликає поклювку.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Тип", "Розмір", "Кількість в упаковці", "Матеріал", "Колір"]
    )
