from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    type_word = (ctx.type_word or "товар для риболовлі").lower()
    intro = [
        f"{ctx.display_name} — {type_word} для практичного використання на водоймі: робоча річ, "
        f"яка спрощує риболовлю.",
        f"{ctx.display_name} — {type_word}, підібраний у каталог за критеріями надійності "
        f"та розумної ціни.",
        f"{ctx.display_name} — {type_word} для рибалок, які цінують порядок у спорядженні "
        f"та готовність до будь-яких умов.",
    ]
    usage = [
        "Ключові параметри наведено в характеристиках нижче — звірте їх із вашими снастями "
        "та умовами ловлі перед замовленням.",
        "Виріб розрахований на регулярне використання в польових умовах: вологу, перепади "
        "температур і транспортування в рюкзаку.",
        "Стане доповненням основного комплекту снастей і виручить у ситуаціях, коли дрібниця "
        "вирішує результат риболовлі.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип", "Матеріал", "Призначення", "Розмір", "Діаметр"])
