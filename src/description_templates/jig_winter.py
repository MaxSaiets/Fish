from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    material = ctx.common_params.get("Матеріал", "вольфрам")
    intro = [
        f"{ctx.display_name} — зимова мормишка ({material.lower()}) для ловлі окуня, плотви "
        f"та підлящика з льоду.",
        f"{ctx.display_name} — мормишка з {material.lower()} зі стабільною грою: компактне тіло "
        f"при солідній вазі швидко доставляє насадку на робочу глибину.",
        f"{ctx.display_name} — зимова приманка з якісним гачком і акуратним вушком: в'язати "
        f"на морозі зручно, а підсічки реалізуються без сходів.",
        f"{ctx.display_name} — мормишка для активного пошуку риби по лунках: виразна гра "
        f"провокує навіть пасивного окуня в глухозим'я.",
    ]
    usage = [
        "Вольфрам тоне швидше за свинець при меншому розмірі — перевага на течії та глибині, "
        "де важливо першим показати рибі насадку.",
        "Працює з мотилем, опаришем і безнасадково: підбирайте частоту гри під настрій риби — "
        "від плавних похитувань до високочастотного дрижання.",
        "Фарбування стійке до подряпин об лід і зуби риби; колір зберігає контраст у сутінках "
        "під льодом.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Матеріал", "Форма", "Вага", "Розмір", "Тип кріплення"]
    )
