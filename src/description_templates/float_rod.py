from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — поплавкове вудилище для акуратної подачі оснастки: легке, "
        f"слухняне, з передбачуваним строєм.",
        f"{ctx.display_name} — вудилище для класичної поплавкової ловлі: тонка вершинка "
        f"показує делікатні поклювки, а бланк впевнено гасить ривки риби.",
        f"{ctx.display_name} — маневрене поплавкове вудилище: швидко розкладається, добре "
        f"лежить у руці та не втомлює кисть за день активної риболовлі.",
    ]
    usage = [
        "Оптимальне для ставків і тихої води: точне закидання під очерет чи бровку, "
        "м'яке виважування карася, плотви та ляща.",
        "Секції стикуються щільно, без люфтів; transport-довжина зручна для поїздок "
        "громадським транспортом і зберігання вдома.",
        "Працює з легкими оснастками: чутливість зберігається навіть із найтоншими "
        "поплавками та повідцями.",
    ]
    return build_standard_description(ctx, intro, usage, ["Тип вудилища", "Довжина", "Стрій"])
