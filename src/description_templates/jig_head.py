from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    intro = [
        f"{ctx.display_name} — джиг-головка для оснащення силікону: гострий гачок і "
        f"надійна фіксація приманки на цівці.",
        f"{ctx.display_name} — джиг-головка з точною вагою: передбачуваний час падіння "
        f"і чіткий контроль дна на будь-якій дистанції.",
        f"{ctx.display_name} — основа джигового монтажу: правильний баланс голівки задає "
        f"приманці робочу гру на проводці й на падінні.",
    ]
    usage = [
        "Вага визначає темп ловлі: легкі — для повільної подачі на мілководді, важкі — "
        "для глибини, течії та далекого закидання.",
        "Гачок тримає заточку після багатьох риболовель, а фіксатор не дає силікону "
        "сповзати після поклювок.",
        "Тримайте в коробці набір вагів під різні умови — зміна голівки часто "
        "перемикає пасивну рибу в режим атаки.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Вага", "Розмір гачка", "Матеріал", "Кількість в упаковці"],
    )
