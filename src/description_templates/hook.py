from __future__ import annotations
from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    hook_type = ctx.common_params.get("Тип", "гачок").lower()
    intro = [
        f"{ctx.display_name} — {hook_type} з хімічно загостреним жалом, яке просікає губу риби "
        f"при мінімальному зусиллі підсічки.",
        f"{ctx.display_name} — {hook_type} з міцної вуглецевої сталі: тримає форму під навантаженням "
        f"і не розгинається на виважуванні гідного трофея.",
        f"{ctx.display_name} — {hook_type} з надійним вушком та антикорозійним покриттям, "
        f"розрахований на інтенсивну ловлю протягом усього сезону.",
        f"{ctx.display_name} — {hook_type} перевіреної геометрії: правильний вигин піддіва "
        f"мінімізує сходи та впевнено тримає рибу до підсака.",
    ]
    usage = [
        "Підходить для поплавкової, фідерної та донної ловлі. Покриття захищає метал від вологи, "
        "тож гачки зберігають гостроту навіть після багатьох риболовель.",
        "Розмірна сітка дозволяє точно підібрати гачок під насадку — від мотиля й опариша "
        "до кукурудзи та бойлів. Жало довго тримає заточку.",
        "Класична форма працює по білій рибі та коропу; акуратне вушко не ріже повідковий "
        "матеріал, а в'язати вузли на ньому зручно навіть на морозі.",
    ]
    return build_standard_description(
        ctx, intro, usage,
        ["Тип", "Розмір", "Матеріал", "Кількість в упаковці"]
    )
