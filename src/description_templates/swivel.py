from __future__ import annotations

from .base import DescriptionContext, build_standard_description


def build_description(ctx: DescriptionContext) -> str:
    el_type = ctx.common_params.get("Тип", "монтажний елемент").lower()
    intro = [
        f"{ctx.display_name} — {el_type} для побудови надійної оснастки: тримає заявлене "
        f"навантаження із запасом міцності.",
        f"{ctx.display_name} — {el_type} з якісної сталі з антикорозійним покриттям: працює "
        f"сезонами без іржі та люфтів.",
        f"{ctx.display_name} — {el_type} для швидкого переоснащення: заміна повідця чи приманки "
        f"займає секунди навіть на морозі чи в сутінках.",
        f"{ctx.display_name} — компактний {el_type}, що не перевантажує оснастку та залишається "
        f"непомітним для обережної риби.",
    ]
    usage = [
        "Використовується у фідерних, коропових і спінінгових монтажах: вільне обертання "
        "прибирає перекручування волосіні на течії та активних проводках.",
        "Акуратні краї не пошкоджують повідковий матеріал, а правильна геометрія тримає "
        "форму під навантаженням на виважуванні.",
        "Зручно тримати в монтажній коробці кілька розмірів: дрібні — для делікатних оснасток, "
        "більші — для важких грузил і трофейної риби.",
    ]
    return build_standard_description(
        ctx,
        intro,
        usage,
        ["Тип", "Матеріал", "Призначення", "Розмір", "Вага", "Кількість в упаковці"],
    )
