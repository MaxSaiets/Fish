def main() -> int:
    env = load_env()
    base_url = env.get("HOROSHOP_BASE_URL", "https://vsedliarybalky.com.ua").rstrip("/")
    session = requests.Session()
    session.headers["User-Agent"] = "fish-sync-pages-improve/1.0"
    auth = session.post(f"{base_url}/core-api/admin/security/login",
                        json={"login": env["HOROSHOP_LOGIN"], "password": env["HOROSHOP_PASS"]},
                        timeout=60, verify=False)
    auth.raise_for_status()

    results = []
    for page_id, page in PAGES.items():
        res = update_page(session, base_url, page_id, page)
        results.append(res)
        print(f"OK {page_id} {page['slug']}")

    verification = {}
    for page in PAGES.values():
        text = visible_text(session, base_url, page["slug"])
        verification[page["slug"]] = {
            "words": len(text.split()),
            "has_h1": page["h1"] in text,
            "has_phone": PHONE in text,
        }
    report = {"updated": results, "verification": verification,
              "finished": datetime.now().isoformat()}
    out = ROOT / "data" / "content_pages_improve_report_20260610.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")
    print(json.dumps(verification, ensure_ascii=False, indent=1))
    return 0


