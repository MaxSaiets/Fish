def post(url, params):
    data = urllib.parse.urlencode(params).encode('utf-8')
    req = urllib.request.Request(url, data=data, headers={
        'Content-Type': 'application/x-www-form-urlencoded',
        'X-Requested-With': 'XMLHttpRequest',
        'Referer': 'http://shop647643.horoshop.ua/adminLegacy/',
    })
    return opener.open(req)

def process(sid, parent, name):
    # Step 1: get slug from widget
    # Always use parent_id=97 (catalog root) - using actual parent_id causes 400 for child sections
    resp = post('http://shop647643.horoshop.ua/_widget/zteel_params_url_Param/updateUriAutomatically', {
        'fields[title]': name,
        'param_id': '1',
        'record_id': sid,
        'parent_id': '97',
    })
    wdata = json.loads(resp.read())
    if wdata.get('status') != 'OK':
        raise Exception(f"Widget error: {wdata}")
    slug = wdata['response']['slug']
    url_parent = str(wdata['response'].get('parent', ''))
    seo = build_seo(name)

    # Step 2: save (NO extra_handler=381!)
    params = {
        'checkcode': 'yamete_kudasai',
        'id': sid,
        'handler': '4',
        'handlertable': 'pages',
        'back': 'index.php',
        'names[parent]': parent,
        'names[name][slug]': slug,
        'names[name][parent]': url_parent,
        'names[name][forceUpdate]': '1',
        'names[i18n][3][title]': name,
        'names[i18n][1][title]': name,
        'names[i18n][3][seo_title]': seo['seo_title'],
        'names[i18n][3][seo_description]': seo['seo_description'],
        'names[i18n][3][seo_keywords]': seo['seo_keywords'],
        'names[i18n][3][h1_title]': seo['h1_title'],
        'names[inmenu]': '1',
        'names[insitemap]': '1',
        'names[noindex]': '0',
        'names[nofollow]': '0',
    }
    resp2 = post('http://shop647643.horoshop.ua/adminLegacy/save.php', params)
    final_url = resp2.url
    return slug, final_url

